"""Canonical query result schema for benchmark evaluations."""

from __future__ import annotations

import math
from enum import StrEnum
from typing import Any, Self

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from rag_benchmark.errors.models import BenchmarkErrorType, StructuredError
from rag_benchmark.schemas.evidence import RetrievedEvidence
from rag_benchmark.schemas.strict_json import validate_strict_json_dict
from rag_benchmark.security.sanitizer import sanitize_dict_for_manifest


class QueryStatus(StrEnum):
    """Execution status for a single benchmark query."""

    SUCCESS = "success"
    FAILED = "failed"
    TIMEOUT = "timeout"
    ERROR = "error"


class QueryUsage(BaseModel):
    """Resource consumption metrics for a query execution."""

    model_config = ConfigDict(frozen=True, extra="forbid", validate_assignment=True)

    llm_calls: int = Field(default=0, ge=0, description="Total number of LLM inference calls.")
    embedding_calls: int = Field(
        default=0, ge=0, description="Total number of embedding API calls."
    )
    input_tokens: int = Field(
        default=0, ge=0, description="Total input prompt tokens consumed by LLM calls."
    )
    output_tokens: int = Field(
        default=0, ge=0, description="Total completion tokens generated by LLM calls."
    )


class QueryTiming(BaseModel):
    """Latency metrics in milliseconds for a query execution."""

    model_config = ConfigDict(frozen=True, extra="forbid", validate_assignment=True)

    retrieval_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Duration spent retrieving documents/evidence in milliseconds.",
    )
    generation_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="Duration spent generating the final answer in milliseconds.",
    )
    total_ms: float = Field(
        default=0.0,
        ge=0.0,
        description="End-to-end total query duration in milliseconds.",
    )

    @field_validator("retrieval_ms", "generation_ms", "total_ms")
    @classmethod
    def validate_finite_time(cls, v: float) -> float:
        if math.isnan(v) or math.isinf(v):
            raise ValueError("Timing values must be finite numbers (no NaN or Infinity)")
        if v < 0.0:
            raise ValueError("Timing values cannot be negative")
        return v


class QueryResult(BaseModel):
    """Canonical benchmark result for a single question evaluation."""

    model_config = ConfigDict(frozen=True, extra="forbid", validate_assignment=True)

    question_id: str = Field(
        ...,
        min_length=1,
        description="Identifier of the benchmark question answered.",
    )
    system: str = Field(
        ...,
        min_length=1,
        description="Name of the RAG system evaluated (e.g. 'traditional_rag').",
    )
    variant: str = Field(
        default="baseline",
        description="Specific variant evaluated (e.g. 'chunk_512', 'graph_hybrid').",
    )
    answer: str | None = Field(
        default=None,
        description="Generated answer in Persian Unicode, or None if failed.",
    )
    status: QueryStatus = Field(
        ...,
        description="Outcome status of the query execution.",
    )
    retrieved_evidence: list[RetrievedEvidence] = Field(
        default_factory=list,
        description="List of retrieved evidence units, maintaining provenance.",
    )
    usage: QueryUsage = Field(
        default_factory=QueryUsage,
        description="Token and call usage statistics.",
    )
    timing: QueryTiming = Field(
        default_factory=QueryTiming,
        description="Retrieval and generation latency breakdown.",
    )
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Strict JSON-native execution metadata.",
    )
    error: StructuredError | None = Field(
        default=None,
        description="Structured error details if status is FAILED, TIMEOUT, or ERROR.",
    )

    @field_validator("question_id", "system")
    @classmethod
    def validate_non_empty_str(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Field cannot be empty or whitespace only")
        return v

    @field_validator("metadata")
    @classmethod
    def validate_metadata(cls, v: dict[str, Any]) -> dict[str, Any]:
        strict = validate_strict_json_dict(v, "metadata")
        return sanitize_dict_for_manifest(strict)

    @model_validator(mode="after")
    def validate_state_matrix(self) -> Self:
        """Validate cross-field state matrix for success vs. failed/error results."""
        if self.status == QueryStatus.SUCCESS:
            if self.error is not None:
                raise ValueError("Successful QueryResult must not contain an error")
            if self.answer is None:
                raise ValueError("Successful QueryResult must have a non-None answer string")
        else:  # FAILED, TIMEOUT, ERROR
            if self.error is None:
                raise ValueError(
                    f"QueryResult with status '{self.status.value}' must include a StructuredError"
                )
            if self.answer is not None:
                raise ValueError(
                    f"Failed QueryResult (status='{self.status.value}') must have answer=None"
                )
            if (
                self.status == QueryStatus.TIMEOUT
                and self.error.error_type != BenchmarkErrorType.TIMEOUT
            ):
                raise ValueError("QueryResult with status TIMEOUT must have error_type=TIMEOUT")

            # Nested error identity verification
            if self.error.question_id is not None and self.error.question_id != self.question_id:
                raise ValueError(
                    f"Error question_id '{self.error.question_id}' does not match "
                    f"result question_id '{self.question_id}'"
                )
            if self.error.system and self.error.system != self.system:
                raise ValueError(
                    f"Error system '{self.error.system}' does not match "
                    f"result system '{self.system}'"
                )
            if self.error.variant and self.error.variant != self.variant:
                raise ValueError(
                    f"Error variant '{self.error.variant}' does not match "
                    f"result variant '{self.variant}'"
                )

        return self

    @classmethod
    def create_success(
        cls,
        question_id: str,
        system: str,
        answer: str,
        variant: str = "baseline",
        retrieved_evidence: list[RetrievedEvidence] | None = None,
        usage: QueryUsage | None = None,
        timing: QueryTiming | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> QueryResult:
        """Helper to create a successful QueryResult."""
        return cls(
            question_id=question_id,
            system=system,
            variant=variant,
            answer=answer,
            status=QueryStatus.SUCCESS,
            retrieved_evidence=retrieved_evidence or [],
            usage=usage or QueryUsage(),
            timing=timing or QueryTiming(),
            metadata=metadata or {},
            error=None,
        )

    @classmethod
    def create_failure(
        cls,
        question_id: str,
        system: str,
        error_message: str,
        variant: str = "baseline",
        error_type: BenchmarkErrorType = BenchmarkErrorType.UNKNOWN,
        status: QueryStatus = QueryStatus.FAILED,
        retrieved_evidence: list[RetrievedEvidence] | None = None,
        usage: QueryUsage | None = None,
        timing: QueryTiming | None = None,
        metadata: dict[str, Any] | None = None,
        retry_count: int = 0,
    ) -> QueryResult:
        """Helper to create a failed QueryResult preserving retrieval evidence and timing."""
        if status == QueryStatus.SUCCESS:
            raise ValueError("create_failure() cannot be called with status=QueryStatus.SUCCESS")

        err = StructuredError(
            question_id=question_id,
            system=system,
            variant=variant,
            error_type=error_type,
            message=error_message,
            retry_count=retry_count,
            metadata=metadata or {},
        )
        return cls(
            question_id=question_id,
            system=system,
            variant=variant,
            answer=None,
            status=status,
            retrieved_evidence=retrieved_evidence or [],
            usage=usage or QueryUsage(),
            timing=timing or QueryTiming(),
            metadata=metadata or {},
            error=err,
        )
